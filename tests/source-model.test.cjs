const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const m = vm.createContext({});
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname, '../SourceModel.js'), 'utf8'), m);
let checks = 0;
function test(name, check) { check(); checks++; console.log('PASS ' + name); }
const chrome = { identity: 'Chromium', dbusName: 'org.mpris.MediaPlayer2.chromium.instance123', trackTitle: 'Song', trackArtist: 'Artist', metadata: {}, isPlaying: true, canTogglePlaying: true };
const tidal = { pid: 123, appId: 'chrome-listen.tidal.com__-Default' };
const whatsapp = { pid: 123, appId: 'chrome-web.whatsapp.com__-Default' };
test('TIDAL origin is identified', () => assert(m.classify({...chrome, metadata: {'xesam:url':'https://listen.tidal.com/track/12'}}, []).verified));
test('TIDAL artwork origin is identified', () => assert(m.classify({...chrome, trackArtUrl:'https://resources.tidal.com/images/cover.jpg'}, []).verified));
test('lookalike domain is rejected', () => assert(!m.tidalUrl('https://tidal.com.evil.test/track/1')));
test('unrelated media apps are excluded', () => assert.equal(m.classify({...chrome, identity:'Spotify', dbusName:'org.mpris.MediaPlayer2.spotify'}, []), null));
test('dedicated TIDAL PWA is identified', () => assert(m.classify(chrome, [tidal]).verified));
test('shared browser remains ambiguous', () => assert(!m.classify(chrome, [tidal, whatsapp]).verified));
test('different PID cannot attribute a browser', () => assert(!m.classify(chrome, [{...tidal, pid:999}]).verified));
test('window title alone cannot attribute a browser', () => assert(!m.classify(chrome, [{pid:123, appId:'chromium', title:'TIDAL'}]).verified));
const rust = {id:'rust', kind:'rust', can_play:true, playing:false, started:1};
const web = {id:'web:123', kind:'web', verified:true, playing:true, can_play:true, started:2};
test('playing web wins over paused native', () => assert.equal(m.select([rust,web], 'auto','rust').id, web.id));
test('playing native wins over paused web', () => assert.equal(m.select([{...rust,playing:true},{...web,playing:false}], 'auto',web.id).id,'rust'));
test('latest started source wins when both play', () => assert.equal(m.select([{...rust,playing:true,started:4},web], 'auto','').id,'rust'));
test('pause holds current source', () => assert.equal(m.select([rust,{...web,playing:false}], 'auto',web.id).id,web.id));
test('ambiguous browser cannot take over Auto', () => assert.equal(m.select([rust,{...web,verified:false}], 'auto','').id,'rust'));
test('explicit browser choice overrides Auto safely', () => assert.equal(m.select([rust,{...web,verified:false}],web.id,'').id,web.id));
test('vanished pinned session never falls through to another', () => assert.equal(m.select([rust,web],'web:gone','rust'),null));
test('no sources is safe', () => assert.equal(m.select([],'auto',''),null));
console.log(`${checks} source selection checks passed`);
